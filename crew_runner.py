# Workaround for CrewAI adding an Anthropic-only cache marker that Groq rejects.
crewai_cache.mark_cache_breakpoint = lambda message: message

MODEL_NAME = "openai/gpt-oss-120b"


def make_llm(api_key: str):
    return LLM(
        model=f"groq/{MODEL_NAME}",
        api_key=api_key,
        temperature=0.1,
    )


def run_agent(agent, description: str, expected_output: str) -> str:
    task = Task(
        description=description,
        expected_output=expected_output,
        agent=agent,
    )
    crew = Crew(
        agents=[agent],
        tasks=[task],
        process=Process.sequential,
        verbose=False,
    )
    return str(crew.kickoff())


def extract_json(text: str) -> dict:
    # Handle JSON wrapped in a Markdown code fence as well as plain JSON.
    cleaned = re.sub(r"```(?:json)?|```", "", text).strip()
    match = re.search(r"\{.*\}", cleaned, re.DOTALL)

    if not match:
        raise ValueError("The reviewer did not return JSON. Please try again.")

    return json.loads(match.group(0))


def find_jobs(
    cv_text: str,
    locations: list[str],
    limit: int,
    api_key: str,
    on_stage,
):
    cv_text = cv_text[:10000]
    llm = make_llm(api_key)

    on_stage("CV Analyst", "Reviewing your pasted CV description")
    profile = run_agent(
        create_cv_analyst(llm, cv_text),
        (
            "Use the CV description reader tool. Extract the candidate's "
            "previous job designations, experience duration if stated, "
            "technical skills, sectors, project types, and software. "
            "Do not include contact details. Keep the profile concise."
        ),
        "A concise factual candidate profile and relevant search keywords.",
    )
    profile = profile[:4000]

    on_stage("Job Scout", "Searching web and public LinkedIn results")
    search_tool = PublicJobSearchTool()
    scout = create_job_scout(llm, search_tool)

    search_evidence = run_agent(
        scout,
        (
            f"Candidate profile:\n{profile}\n\n"
            f"Target locations: {', '.join(locations)}.\n"
            "Search for current civil engineering jobs relevant to the "
            "candidate's actual previous designations and stated experience. "
            "Use the Public web and LinkedIn job search tool. Search the "
            "public web, publicly indexed LinkedIn job pages, and public "
            "company hiring posts. Do not claim access to private LinkedIn "
            "content. Return concise evidence and original URLs. Do not "
            "invent any job details."
        ),
        "Concise public search evidence with original job URLs.",
    )

    # Use exact URLs captured by our tool. Do not trust URLs generated by the LLM.
    verified_source_results = search_tool.search_results[:15]
    evidence_json = json.dumps(verified_source_results, ensure_ascii=False)[:9000]

    on_stage("Match Reviewer", "Comparing search evidence with your experience")
    reviewed = run_agent(
        create_match_reviewer(llm),
        (
            f"Candidate profile:\n{profile}\n\n"
            f"Original search evidence from the search tool:\n{evidence_json}\n\n"
            f"Scout notes:\n{search_evidence[:2000]}\n\n"
            "Return ONLY valid JSON with this structure:\n"
            "{"
            '"profile_summary": "string", '
            '"jobs": ['
            "{"
            '"title": "string", '
            '"company": "string", '
            '"location": "string", '
            '"url": "string", '
            '"source_type": "string", '
            '"match_score": 0, '
            '"why_match": "string", '
            '"requirements": "string"'
            "}"
            "], "
            '"notes": "string"'
            "}\n"
            f"Return at most {limit} jobs. Every URL must exactly match a URL "
            "in the original search evidence. Do not invent a listing. "
            "Scores are approximate review aids, not probabilities or hiring "
            "decisions. Explain the experience and designation alignment."
        ),
        "Valid JSON with verified-source URLs and cautious match explanations.",
    )

    data = extract_json(reviewed)

    allowed_urls = {
        item["url"] for item in verified_source_results if item.get("url")
    }

    filtered_jobs = []
    for job in data.get("jobs", []):
        if job.get("url") not in allowed_urls:
            continue

        # Attach the original snippet so the user can judge the evidence.
        source = next(
            item for item in verified_source_results
            if item["url"] == job["url"]
        )
        job["source_type"] = source["source_type"]
        job["source_snippet"] = source["snippet"]
        filtered_jobs.append(job)

    data["jobs"] = filtered_jobs[:limit]
    return profile, data


def tailor_cv(cv_text: str, selected_job: dict, api_key: str) -> str:
    llm = make_llm(api_key)
    agent = create_cv_tailor(llm)

    task_description = (
        "Create an editable plain-text CV draft for this job.\n\n"
        f"USER'S CV DESCRIPTION:\n{cv_text[:10000]}\n\n"
        "JOB SELECTED BY USER:\n"
        f"Designation: {selected_job.get('title', '')}\n"
        f"Company: {selected_job.get('company', '')}\n"
        f"Location: {selected_job.get('location', '')}\n"
        f"Requirements: {selected_job.get('requirements', '')}\n"
        f"Match explanation: {selected_job.get('why_match', '')}\n\n"
        "Use these headings: PROFESSIONAL SUMMARY, TARGET DESIGNATIONS, "
        "KEY SKILLS, PROFESSIONAL EXPERIENCE, EDUCATION AND CERTIFICATIONS, "
        "GAPS TO REVIEW. Emphasize relevant designations and experience from "
        "the pasted CV. Do not invent facts. Return only the CV draft."
    )

    return run_agent(
        agent,
        task_description,
        "An editable CV draft based only on facts supplied by the user.",
    )
